CREATE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

--changeset tails:001-updated-at-triggers
CREATE TRIGGER trg_admin_updated_at
    BEFORE UPDATE ON admin
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_shelter_updated_at
    BEFORE UPDATE ON shelter
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_animal_updated_at
    BEFORE UPDATE ON animal
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_application_updated_at
    BEFORE UPDATE ON adoption_application
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

--changeset tails:001-fill-shelter splitStatements:false
CREATE FUNCTION fill_application_shelter()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    SELECT shelter_id INTO NEW.shelter_id
    FROM animal
    WHERE id = NEW.animal_id;
    RETURN NEW;
END;
$$;

--changeset tails:001-fill-shelter-trigger
CREATE TRIGGER trg_application_fill_shelter
    BEFORE INSERT OR UPDATE OF animal_id ON adoption_application
    FOR EACH ROW
    EXECUTE FUNCTION fill_application_shelter();
