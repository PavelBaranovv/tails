--changeset tails:001-schema
CREATE TABLE district (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(128) NOT NULL,
    created_at timestamp NOT NULL DEFAULT now(),
    CONSTRAINT uq_district_name UNIQUE (name)
);

CREATE TABLE admin (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    full_name varchar(128),
    created_at timestamp NOT NULL DEFAULT now(),
    updated_at timestamp
);

CREATE UNIQUE INDEX uq_admin_email ON admin (lower(email));

CREATE TABLE shelter (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(256) NOT NULL,
    district_id smallint NOT NULL,
    address varchar(256) NOT NULL,
    phone varchar(18) NOT NULL,
    email varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    status varchar(20) NOT NULL,
    created_at timestamp NOT NULL DEFAULT now(),
    updated_at timestamp,
    CONSTRAINT fk_shelter_district FOREIGN KEY (district_id) REFERENCES district (id) ON DELETE RESTRICT,
    CONSTRAINT chk_shelter_name CHECK (char_length(name) BETWEEN 2 AND 256),
    CONSTRAINT chk_shelter_address CHECK (char_length(address) BETWEEN 2 AND 256),
    CONSTRAINT chk_shelter_phone CHECK (char_length(phone) BETWEEN 7 AND 18),
    CONSTRAINT chk_shelter_status CHECK (status IN ('ACTIVE', 'BLOCKED', 'PENDING'))
);

CREATE UNIQUE INDEX uq_shelter_email ON shelter (lower(email));
CREATE INDEX idx_shelter_district_id ON shelter (district_id);

CREATE TABLE shelter_registration_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(256) NOT NULL,
    district_id smallint NOT NULL,
    address varchar(256) NOT NULL,
    full_name varchar(128) NOT NULL,
    phone varchar(18) NOT NULL,
    email varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    status varchar(20) NOT NULL,
    created_at timestamp NOT NULL DEFAULT now(),
    processed_at timestamp,
    CONSTRAINT fk_registration_district FOREIGN KEY (district_id) REFERENCES district (id) ON DELETE RESTRICT,
    CONSTRAINT chk_registration_name CHECK (char_length(name) BETWEEN 2 AND 256),
    CONSTRAINT chk_registration_address CHECK (char_length(address) BETWEEN 2 AND 256),
    CONSTRAINT chk_registration_full_name CHECK (char_length(full_name) BETWEEN 2 AND 128),
    CONSTRAINT chk_registration_phone CHECK (char_length(phone) BETWEEN 7 AND 18),
    CONSTRAINT chk_registration_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_registration_district_id ON shelter_registration_request (district_id);

CREATE TABLE animal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shelter_id bigint NOT NULL,
    name varchar(64) NOT NULL,
    species varchar(32) NOT NULL,
    species_other varchar(64),
    breed varchar(64),
    gender varchar(10),
    birth_month smallint,
    birth_year smallint,
    description varchar(1024),
    status varchar(20) NOT NULL,
    created_at timestamp NOT NULL DEFAULT now(),
    updated_at timestamp,
    CONSTRAINT fk_animal_shelter FOREIGN KEY (shelter_id) REFERENCES shelter (id) ON DELETE CASCADE,
    CONSTRAINT chk_animal_name CHECK (char_length(name) BETWEEN 2 AND 64),
    CONSTRAINT chk_animal_species CHECK (species IN ('CAT', 'DOG', 'PARROT', 'OTHER')),
    CONSTRAINT chk_animal_species_other CHECK (
        (species = 'OTHER' AND species_other IS NOT NULL AND char_length(species_other) BETWEEN 1 AND 64)
        OR (species <> 'OTHER' AND species_other IS NULL)
    ),
    CONSTRAINT chk_animal_gender CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE')),
    CONSTRAINT chk_animal_birth_month CHECK (birth_month IS NULL OR birth_month BETWEEN 1 AND 12),
    CONSTRAINT chk_animal_birth_consistency CHECK (birth_month IS NULL OR birth_year IS NOT NULL),
    CONSTRAINT chk_animal_description CHECK (
        description IS NULL OR char_length(description) BETWEEN 8 AND 1024
    ),
    CONSTRAINT chk_animal_status CHECK (status IN ('HIDDEN', 'AVAILABLE', 'ADOPTED'))
);

CREATE INDEX idx_animal_shelter_id ON animal (shelter_id);

CREATE TABLE animal_photo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id bigint NOT NULL,
    object_key varchar(512) NOT NULL,
    is_main boolean NOT NULL DEFAULT false,
    sort_order smallint NOT NULL DEFAULT 0,
    content_type varchar(32) NOT NULL,
    size_bytes integer,
    created_at timestamp NOT NULL DEFAULT now(),
    CONSTRAINT fk_photo_animal FOREIGN KEY (animal_id) REFERENCES animal (id) ON DELETE CASCADE,
    CONSTRAINT chk_photo_content_type CHECK (content_type IN ('image/jpeg', 'image/png')),
    CONSTRAINT chk_photo_size CHECK (size_bytes IS NULL OR size_bytes BETWEEN 0 AND 5242880)
);

CREATE INDEX idx_photo_animal_id ON animal_photo (animal_id);
CREATE UNIQUE INDEX uq_animal_main_photo ON animal_photo (animal_id) WHERE is_main;

CREATE TABLE adoption_application (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id bigint NOT NULL,
    shelter_id bigint NOT NULL,
    applicant_name varchar(128) NOT NULL,
    applicant_phone varchar(18) NOT NULL,
    status varchar(20) NOT NULL,
    created_at timestamp NOT NULL DEFAULT now(),
    updated_at timestamp,
    CONSTRAINT fk_application_animal FOREIGN KEY (animal_id) REFERENCES animal (id) ON DELETE CASCADE,
    CONSTRAINT fk_application_shelter FOREIGN KEY (shelter_id) REFERENCES shelter (id) ON DELETE CASCADE,
    CONSTRAINT chk_application_name CHECK (char_length(applicant_name) BETWEEN 2 AND 128),
    CONSTRAINT chk_application_phone CHECK (char_length(applicant_phone) BETWEEN 7 AND 18),
    CONSTRAINT chk_application_status CHECK (status IN ('NEW', 'IN_PROGRESS', 'PROCESSED'))
);

CREATE INDEX idx_application_animal_id ON adoption_application (animal_id);
CREATE INDEX idx_application_shelter_id ON adoption_application (shelter_id);

